    private boolean periksaNpm() {
    return tandai(
        npmField,
        npmPesanLabel,
        PerpustakaanValidator.npm(npmField.getText())
    );
}

private boolean periksaNama() {
    return tandai(
        namaField,
        namaPesanLabel,
        PerpustakaanValidator.nama(namaField.getText())
    );
}

private boolean periksaProdi() {
    String kesalahan = null;

    if (prodiComboBox.getSelectedIndex() == 0) {
        kesalahan = "Pilih salah satu program studi";
    }

    return tandai(prodiComboBox, prodiPesanLabel, kesalahan);
}

private boolean periksaEmail() {
    return tandai(
        emailField,
        emailPesanLabel,
        PerpustakaanValidator.email(emailField.getText())
    );
}

private boolean periksaHp() {
    return tandai(
        hpField,
        hpPesanLabel,
        PerpustakaanValidator.nomorHp(hpField.getText())
    );
}

private boolean tandai(
        javax.swing.JComponent isian,
        javax.swing.JLabel pesan,
        String kesalahan) {

    isian.putClientProperty(
        "JComponent.outline",
        (kesalahan == null) ? null : "error"
    );

    pesan.setText(
        (kesalahan == null) ? " " : kesalahan
    );

    return kesalahan == null;
}

private void daftar() {

    java.util.List<javax.swing.JComponent> salah =
        new java.util.ArrayList<>();

    if (!periksaNpm()) {
        salah.add(npmField);
    }

    if (!periksaNama()) {
        salah.add(namaField);
    }

    if (!periksaProdi()) {
        salah.add(prodiComboBox);
    }

    if (!periksaEmail()) {
        salah.add(emailField);
    }

    if (!periksaHp()) {
        salah.add(hpField);
    }

    if (!salah.isEmpty()) {
        statusLabel.setText(
            salah.size() + " isian perlu diperbaiki"
        );

        salah.get(0).requestFocusInWindow();
        return;
    }

    statusLabel.setText(" ");

    String pesan = "Pendaftaran berhasil."
            + "\n\nNPM: " + npmField.getText()
            + "\nNama: " + namaField.getText().trim()
            + "\nProgram Studi: "
            + prodiComboBox.getSelectedItem()
            + "\nJenis Anggota: " + jenisAnggota();

    javax.swing.JOptionPane.showMessageDialog(
        this,
        pesan,
        "Pendaftaran Berhasil",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    kosongkan();
}

private String jenisAnggota() {

    if (dosenRadioButton.isSelected()) {
        return "Dosen";
    }

    if (umumRadioButton.isSelected()) {
        return "Umum";
    }

    return "Mahasiswa";
}

private void batal() {

    if (adaIsian()) {

        int jawab = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Data yang sudah diisi akan dihapus. Lanjutkan?",
            "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (jawab != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }
    }

    kosongkan();
}

private boolean adaIsian() {

    return !npmField.getText().isBlank()
            || !namaField.getText().isBlank()
            || !emailField.getText().isBlank()
            || !hpField.getText().isBlank()
            || !alamatTextArea.getText().isBlank();
}

private void kosongkan() {

    npmField.setText("");
    namaField.setText("");
    emailField.setText("");
    hpField.setText("");
    alamatTextArea.setText("");

    prodiComboBox.setSelectedIndex(0);

    mahasiswaRadioButton.setSelected(true);
    setujuCheckBox.setSelected(false);

    digitLabel.setText("0 dari 10 digit");

    tandai(npmField, npmPesanLabel, null);
    tandai(namaField, namaPesanLabel, null);
    tandai(prodiComboBox, prodiPesanLabel, null);
    tandai(emailField, emailPesanLabel, null);
    tandai(hpField, hpPesanLabel, null);

    statusLabel.setText(" ");

    npmField.requestFocusInWindow();
}



