    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // 1. Nama wajib diisi (spasi saja dianggap kosong)
        String nama = txtNama.getText().trim();
        if (nama.isEmpty()) {
            tampilkanKesalahan("Nama barang wajib diisi", txtNama);
            return;
        }

        // 2. Nama tidak boleh ganda (huruf besar dan kecil dianggap sama)
        if (modelTabel.sudahAda(nama)) {
            tampilkanKesalahan("Barang " + nama + " sudah ada di daftar", txtNama);
            return;
        }

        // 3. Harga: angka bulat 1 sampai 10000000 tanpa titik
        long harga = bacaHarga(txtHarga.getText().trim());
        if (harga < 0) {
            tampilkanKesalahan("Harga harus angka 1 sampai 10000000", txtHarga);
            return;
        }

        Kategori kategori = Kategori.dariLabel((String) cmbKategori.getSelectedItem());
        int jumlah = bacaJumlah();

        modelTabel.tambahBarang(new Barang(nama, kategori, harga, jumlah));
        kosongkanForm();
        perbaruiRingkasan();
    }//GEN-LAST:event_btnTambahActionPerformed

