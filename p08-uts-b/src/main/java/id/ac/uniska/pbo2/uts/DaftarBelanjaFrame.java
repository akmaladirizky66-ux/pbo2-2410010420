    /**
     * Mengubah teks harga menjadi angka.
     * Mengembalikan -1 jika bukan angka bulat 1 sampai 10000000 tanpa titik.
     */
    private long bacaHarga(String teks) {
        if (!teks.matches("[0-9]+") || teks.length() > PANJANG_HARGA_MAKSIMUM) {
            return -1;
        }
        long harga = Long.parseLong(teks);
        if (harga < 1 || harga > HARGA_MAKSIMUM) {
            return -1;
        }
        return harga;
    }

    private int bacaJumlah() {
        try {
            spnJumlah.commitEdit(); // ambil teks yang baru diketik di spinner
        } catch (ParseException e) {
            // teks tidak valid: pakai nilai terakhir yang sah di model spinner
        }
        return (Integer) spnJumlah.getValue();
    }

